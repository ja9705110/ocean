"use client";

/**
 * 把投影畫面的尺度釘死在視窗上（C38）。
 *
 * 要解決的問題：後台縮小，投影出去的大螢幕跟著縮小。
 *
 * 那不是兩個畫面在互通，是瀏覽器的設計——Chrome 與 Edge 的縮放是
 * 「每個網站一份」，不是每個視窗一份。後台與大螢幕是同一個網域，
 * 所以在後台按 Ctrl 加減號，另一個視窗立刻跟著變。
 *
 * 本來不該有事：畫面裡的河、餅乾、角色都是照量到的視窗寬度算的，
 * 縮放時視窗的 CSS 寬度會等比例變大，抵銷掉，投出來的實體大小不變。
 *
 * 真正會動的是文字。Tailwind 的字級與間距幾乎都是 rem，而 rem 跟著
 * 根元素的字級走，預設 16px——那是一個固定的 CSS 長度，縮放一改就跟著縮。
 * 於是河沒變、字變小了，看起來就是「大螢幕跑版」。
 *
 * 做法是把根元素的字級本身也變成視窗的比例。1920 寬時剛好是 16px，
 * 也就是現在的樣子一個像素都不會變；縮放時 100vw 永遠等於整個視窗，
 * 所以投出來的實體大小不動。
 *
 * 順帶解決另一件事：以前在筆電（1920）上調好的版面，換到
 * 1280×720 的投影機上，河與餅乾照比例縮了、字卻沒有，整個比例會跑掉。
 * 現在兩邊一起縮，任何解析度看起來都一樣。
 *
 * 只掛在大螢幕那兩個路由上。手機與後台維持瀏覽器原本的字級——
 * 那些畫面是給人在近處讀的，該讓使用者自己的字級偏好生效。
 */

/**
 * 設計基準：1920 × 1080 時根字級為 16px，等同瀏覽器預設。
 *
 * 除數就是這麼來的：1920 / 16 = 120，1080 / 16 = 67.5。
 * 取兩者較小的，視窗比 16:9 更扁或更窄時才不會撐出畫面。
 *
 * 下限 9px 是給「主持人用手機點開大螢幕確認一下」用的。
 * 投影機再舊也有 1024 寬（8.5px），差那 0.5px 看不出來，
 * 但手機的 390 寬會算出 3.25px，那整頁就沒東西讀得到了。
 */
const ROOT_FONT_SIZE =
  "max(9px, min(calc(100vw / 120), calc(100vh / 67.5)))";

export function ProjectionScale() {
  return <style>{`:root { font-size: ${ROOT_FONT_SIZE}; }`}</style>;
}
